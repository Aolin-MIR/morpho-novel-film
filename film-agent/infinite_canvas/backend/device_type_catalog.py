DEVICE_TYPES = [dict(id=i, label=label, group=group, definition=definition, guidance=guidance)
                for i, label, group, definition, guidance in _ROWS]


def guides(devices):
    selected = {d.get('device_type') for d in devices}
    return [dict(item) for item in DEVICE_TYPES if item['id'] in selected]
