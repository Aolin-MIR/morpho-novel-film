export const entryText = (locale: Locale, text: string): string => locale === 'en' ? (english[text] || text) : text;

export function entryMessage(locale:Locale,value:unknown):string {
 const raw=systemMessage(value,locale==='en'?'the selected model':'所选模型');
 if(locale!=='en')return raw;
 const exact=entryText(locale,raw);if(exact!==raw)return exact;
 const patterns:Array<[RegExp,(...parts:string[])=>string]>=[
  [/^第 (\d+)\/(\d+) 块[：:]?\s*(.*)$/,(_,n,total,step)=>`Section ${n}/${total}: ${entryMessage(locale,step)}`],
  [/^正在校正(.+)[：:](.+)$/,(_,area,reason)=>`Correcting ${entryText(locale,area)}: ${entryMessage(locale,reason)}`],
  [/^已返回场面正文，共 (\d+) 字$/,(_,n)=>`Scene text received: ${n} characters.`],
  [/^模型服务返回 HTTP (\d+)$/,(_,n)=>`The model provider returned an error (HTTP ${n}).`],
  [/^(.+)，正在自动重试（(\d+)\/(\d+)）$/,(_,cause,n,total)=>`${entryMessage(locale,cause)}. Retrying (${n}/${total})…`],
  [/^(.+)；已自动重试两次，现有内容已保留，可稍后继续。$/,(_,cause)=>`${entryMessage(locale,cause)}. Two retries were attempted. Your draft is saved; you can continue later.`],
  [/^timeout of (\d+)ms exceeded$/,(_,n)=>`No response arrived within ${Math.round(Number(n)/1000)} seconds. You can try again.`],
 ];
 for(const [pattern,translate] of patterns){const match=raw.match(pattern);if(match)return translate(...match);}
 return raw;
}
